def main():
    text = PPT.read_text(encoding="utf-8")
    for name, old, new in PATCHES:
        if new in text and old not in text:
            print(f"[skip] {name}")
            continue
        n = text.count(old)
        assert n == 1, f"{name} 命中 {n} 次"
        text = text.replace(old, new)
        print(f"[ok]   {name}")
